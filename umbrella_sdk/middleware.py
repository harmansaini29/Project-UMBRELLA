"""
Project UMBRELLA: FastAPI / Starlette Middleware
Transparently intercepts unhandled microservice exceptions, records real-time latency,
and dispatches incident packets to UMBRELLA Mission Control.
"""

import time
import logging
from starlette.middleware.base import BaseHTTPMiddleware
from starlette.requests import Request
from starlette.responses import Response, JSONResponse

from umbrella_sdk.client import UmbrellaClient

logger = logging.getLogger("umbrella_sdk.middleware")


class UmbrellaFastAPIMiddleware(BaseHTTPMiddleware):
    """
    Middleware that seamlessly connects any FastAPI microservice into Project UMBRELLA.
    """

    def __init__(self, app, client: UmbrellaClient):
        super().__init__(app)
        self.client = client

    async def dispatch(self, request: Request, call_next) -> Response:
        start_time = time.time()
        try:
            response = await call_next(request)
            elapsed_ms = (time.time() - start_time) * 1000.0

            # If response is 500 status code generated by framework
            if response.status_code >= 500:
                logger.warning(f"[UMBRELLA SDK] HTTP {response.status_code} detected on {request.method} {request.url.path}")

            return response

        except Exception as exc:
            elapsed_ms = (time.time() - start_time) * 1000.0
            logger.error(f"[UMBRELLA SDK] Unhandled Exception on {request.method} {request.url.path}: {exc}")

            # Send telemetry and incident to UMBRELLA Mission Control
            context = {
                "http_method": request.method,
                "path": str(request.url.path),
                "elapsed_ms": elapsed_ms,
                "client_ip": request.client.host if request.client else "unknown"
            }
            try:
                self.client.report_incident(exc, context=context)
            except Exception as report_err:
                logger.error(f"[UMBRELLA SDK] Failed to dispatch incident to Mission Control: {report_err}")

            # Return 500 JSON response
            return JSONResponse(
                status_code=500,
                content={
                    "error": "Internal Server Error",
                    "exception": type(exc).__name__,
                    "detail": str(exc),
                    "umbrella_monitored": True,
                    "remediation_in_progress": True
                }
            )
